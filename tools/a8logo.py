#!/usr/bin/env python3
"""Make the A8 boot shim's logo from the user's own IPSW (nothing Apple-made is stored in this repo).

  a8logo.py IPSW OUT.h        -> C header: a8_logo_w, a8_logo_h, a8_logo[] (8-bit coverage, row-major)

Reads Firmware/all_flash/applelogo@3x~iphone.im4p (or @2x), the iBoot "iBootIm" image (LZSS, 'grey' = luma+alpha
or 'argb'), and keeps one byte per pixel (alpha * luma / 255): the shim draws it white-on-black, centred.
"""
import struct, sys, zipfile

ipsw, out = sys.argv[1], sys.argv[2]
z = zipfile.ZipFile(ipsw)
names = [n for n in z.namelist() if 'applelogo@3x' in n and n.endswith('.im4p')] or \
        [n for n in z.namelist() if 'applelogo' in n and n.endswith('.im4p')]
if not names:
    raise SystemExit('no applelogo*.im4p in ' + ipsw)
d = z.read(sorted(names)[0])
i = d.find(b'iBootIm\0')
if i < 0:
    raise SystemExit('no iBootIm payload')
hdr = d[i:i + 0x40]
comp, fmt = hdr[12:16][::-1], hdr[16:20][::-1]
w, h = struct.unpack('<HH', hdr[20:24])
src = d[i + 0x40:]


def lzss(src, size):
    # Classic Okumura LZSS (N=4096, F=18, threshold 2), as iBoot uses.
    N, F, T = 4096, 18, 2
    text = bytearray(b' ' * (N + F - 1))
    r, out, p, flags = N - F, bytearray(), 0, 0
    while len(out) < size and p < len(src):
        flags >>= 1
        if not flags & 0x100:
            flags = src[p] | 0xff00
            p += 1
        if flags & 1:
            c = src[p]; p += 1
            out.append(c); text[r] = c; r = (r + 1) & (N - 1)
        else:
            if p + 1 >= len(src):
                break
            a, b = src[p], src[p + 1]; p += 2
            pos = a | ((b & 0xf0) << 4)
            ln = (b & 0x0f) + T
            for k in range(ln + 1):
                c = text[(pos + k) & (N - 1)]
                out.append(c); text[r] = c; r = (r + 1) & (N - 1)
    return bytes(out)


bpp = 2 if fmt == b'grey' else 4
raw = lzss(src, w * h * bpp) if comp == b'lzss' else src[:w * h * bpp]
if len(raw) < w * h * bpp:
    raise SystemExit(f'short image {len(raw)} < {w * h * bpp} ({comp} {fmt})')
cov = bytearray(w * h)
for k in range(w * h):
    if bpp == 2:
        g, a = raw[2 * k], raw[2 * k + 1]
    else:
        b_, g_, r_, a = raw[4 * k:4 * k + 4]
        g = max(r_, g_, b_)
    cov[k] = 255 - g * a // 255     # the 'grey' logo is dark on a light ground; the shim wants logo = 255
with open(out, 'w') as f:
    f.write(f'/* generated by tools/a8logo.py from the local IPSW; not part of the repo */\n')
    f.write(f'static const unsigned a8_logo_w = {w}, a8_logo_h = {h};\n')
    f.write('static const unsigned char a8_logo[] = {\n')
    for k in range(0, len(cov), 24):
        f.write(','.join(str(x) for x in cov[k:k + 24]) + ',\n')
    f.write('};\n')
print(f'{out}: {w}x{h} {fmt.decode()} {comp.decode()}')
